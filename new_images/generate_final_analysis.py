def generate_final():
    headers = [
        "كود المنتج",
        "اسم المنتج التجاري",
        "اسم المنتج بالمتجر",
        "وصف المنتج",
        "أقل سعر مستهلك (ج.م)",
        "أعلى سعر مستهلك (ج.م)",
        "احطياطي مخزون",
        "سعر الجمله",
        "رابط الصورة المحلي"
    ]
    
    rows = []
    rows.append(headers)
    
    valid_exts = ('.jpg', '.png', '.jpeg', '.mp4')
    
    try:
        files = os.listdir(img_dir)
    except FileNotFoundError:
        print("Dir not found")
        return
        
    for filename in files:
        if filename.lower().endswith(valid_exts):
            base_code, _ = os.path.splitext(filename)
            file_url = f"file:///C:/Users/FOX/Desktop/فرح%20لستور/new_images/{filename}"
            
            # 1. Try to get from original CSV (the 26 they already filled out)
            if base_code in known_data:
                kd = known_data[base_code]
                row = [
                    base_code,
                    kd[1], # التجاري
                    kd[2], # بالمتجر
                    kd[3], # الوصف
                    kd[4], # اقل
                    kd[5], # اعلى
                    kd[6] if len(kd)>6 else "30", # مخزون
                    kd[7] if len(kd)>7 else "150", # جملة
                    file_url
                ]
            # 2. Use AI analyzed data for the missing 17
            elif base_code in ai_data:
                d = ai_data[base_code]
                row = [
                    base_code,
                    d[0], d[1], d[2], d[3], d[4], d[5], d[6],
                    file_url
                ]
            else:
                # Fallback for anything else
                row = [base_code, "منتج جديد", "منتج جديد", "وصف المنتج", "100", "200", "10", "80", file_url]
                
            rows.append(row)
            
    with open(csv_file, 'w', encoding='utf-8-sig', newline='') as f:
        writer = csv.writer(f, quoting=csv.QUOTE_MINIMAL)
        writer.writerows(rows)
        
    print(f"Success! Generated complete CSV with {len(rows)-1} products.")

if __name__ == "__main__":
    generate_final()
